// Daftar negara dan bendera untuk pilihan "Negara" di edit profil.
// Bendera dibuat dari kode ISO negara (regional indicator) sehingga tidak
// butuh aset gambar dan tetap tampil di semua perangkat Android.

class Negara {
  const Negara(this.kode, this.nama);

  final String kode;
  final String nama;

  String get bendera => benderaNegara(kode);
}

/// Bendera dari kode ISO dua huruf, misal "ID" menjadi bendera Indonesia.
String benderaNegara(String? kode) {
  final String k = (kode ?? '').trim().toUpperCase();
  if (k.length != 2) {
    return '';
  }
  for (int i = 0; i < 2; i++) {
    final int c = k.codeUnitAt(i);
    if (c < 65 || c > 90) {
      return '';
    }
  }
  return String.fromCharCodes(<int>[
    0x1F1E6 + (k.codeUnitAt(0) - 65),
    0x1F1E6 + (k.codeUnitAt(1) - 65),
  ]);
}

/// Nama negara dari kode ISO.
String namaNegara(String? kode) {
  final String k = (kode ?? '').trim().toUpperCase();
  for (final Negara n in kDaftarNegara) {
    if (n.kode == k) {
      return n.nama;
    }
  }
  return '';
}

